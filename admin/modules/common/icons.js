function icon(name, size) {
  const paths = ICON_PATHS[name];
  if (!paths) return '';
  const s = size || '1em';
  return `<svg viewBox="0 0 24 24" width="${s}" height="${s}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" style="vertical-align:-0.125em;flex-shrink:0;" aria-hidden="true">${paths}</svg>`;
}

function renderIconEl(el) {
  if (el.dataset.iconRendered) return;
  const svg = icon(el.dataset.icon, el.dataset.iconSize);
  if (!svg) return;
  el.innerHTML = svg;
  el.dataset.iconRendered = '1';
  if (!el.style.display) el.style.display = 'inline-flex';
  el.style.alignItems = 'center';
}

function renderIconsIn(root) {
  if (root.nodeType !== 1 && root.nodeType !== 9) return;
  if (root.nodeType === 1 && root.matches('[data-icon]')) renderIconEl(root);
  root.querySelectorAll('[data-icon]').forEach(renderIconEl);
}

// Render existing icons and watch for dynamically added ones
(function initIcons() {
  const start = () => {
    renderIconsIn(document);
    new MutationObserver(mutations => {
      for (const m of mutations) {
        m.addedNodes.forEach(n => { if (n.nodeType === 1) renderIconsIn(n); });
      }
    }).observe(document.body, { childList: true, subtree: true });
  };
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
})();
